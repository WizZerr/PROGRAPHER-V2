from __future__ import annotations

import argparse
import shutil
from pathlib import Path

import cv2
import numpy as np

from jpeg_j0_feasibility import _apply_recipe_uint8, _write_jpeg
from jpeg_j1_synthetic_brain import (
    _ground_truth_recipe,
    _make_scene,
    extract_features,
)


EVENT_COUNT = 12
IMAGES_PER_EVENT = 18


def _photographer_style(recipe: np.ndarray) -> np.ndarray:
    styled = recipe.copy()

    # One fixed synthetic "photographer style" on top of the image-dependent
    # recipe. The intercept of J1 can learn this constant preference while the
    # measured features explain per-image corrections.
    styled[0] += [0.010, 0.004, -0.008]
    styled[1, 0] += 0.018
    styled[2, 1] += 0.012
    styled[3, 2] -= 0.010
    styled[4, 0] += 0.012
    styled[5, 1] += 0.010
    styled[6, 2] += 0.008
    return styled


def _read_rgb(path: Path) -> np.ndarray:
    payload = np.frombuffer(path.read_bytes(), dtype=np.uint8)
    image = cv2.imdecode(payload, cv2.IMREAD_COLOR)
    if image is None:
        raise RuntimeError(f"Could not decode generated JPEG: {path}")
    return cv2.cvtColor(image, cv2.COLOR_BGR2RGB)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Create a deterministic multi-event JPEG fixture whose edits follow a "
            "learnable image-dependent recipe plus one fixed photographer style. "
            "This exercises the real intake -> J0 targets -> J1 candidate path."
        )
    )
    parser.add_argument("--output", required=True)
    parser.add_argument("--clean", action="store_true")
    parser.add_argument("--width", type=int, default=640)
    parser.add_argument("--height", type=int, default=426)
    parser.add_argument("--jpeg-quality", type=int, default=98)
    args = parser.parse_args()

    output = Path(args.output).expanduser().resolve()
    if args.clean and output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True, exist_ok=True)

    width = max(320, int(args.width))
    height = max(220, int(args.height))
    quality = min(100, max(90, int(args.jpeg_quality)))

    for event_index in range(EVENT_COUNT):
        event_id = f"event_{event_index + 1:02d}"
        event_root = output / event_id
        originals = event_root / "ORIGINALS"
        edits = event_root / "EDITS"
        originals.mkdir(parents=True, exist_ok=True)
        edits.mkdir(parents=True, exist_ok=True)

        for image_index in range(IMAGES_PER_EVENT):
            sample_name = f"IMG_{event_index + 1:02d}_{image_index + 1:03d}.jpg"
            original_path = originals / sample_name
            edited_path = edits / sample_name

            generated = _make_scene(
                event_index=event_index,
                image_index=image_index,
                width=width,
                height=height,
            )
            _write_jpeg(original_path, generated, quality=quality)

            # Build the target from the persisted JPEG bytes so the feature
            # contract matches what the real J1 candidate will see later.
            original = _read_rgb(original_path)
            features = extract_features(original)
            recipe = _photographer_style(_ground_truth_recipe(features))
            edited = _apply_recipe_uint8(original, recipe)
            _write_jpeg(edited_path, edited, quality=quality)

    print("=" * 80)
    print("ProGrapher — JPEG real-learning smoke fixture")
    print("=" * 80)
    print(f"Events:                           {EVENT_COUNT}")
    print(f"Images per event:                 {IMAGES_PER_EVENT}")
    print(f"Total pairs:                      {EVENT_COUNT * IMAGES_PER_EVENT}")
    print("Expected auto split:              train=8 validation=2 test=2")
    print(f"Fixture root:                     {output}")
    print()
    print(
        "Edits are generated by an image-dependent recipe plus a fixed synthetic "
        "photographer style. This is engineering data only."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
